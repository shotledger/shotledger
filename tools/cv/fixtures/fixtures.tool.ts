const LIMIT = 2 ** 53;

function closeupLockFixture() {
  const width = 1024;
  const height = 768;
  return {
    workLongSide: CLOSEUP_WORK_LONG_SIDE,
    blackR: CLOSEUP_DRAWING.blackR,
    rings: [...CLOSEUP_DRAWING.rings],
    lineHalf: CLOSEUP_DRAWING.lineHalf,
    holeR: CLOSEUP_DRAWING.holeR,
    gate: {
      residualMm: new F(CLOSEUP_GATE.residualMm),
      comb: new F(CLOSEUP_GATE.comb),
      ringOffsetMm: new F(CLOSEUP_GATE.ringOffsetMm),
      faceContrast: new F(CLOSEUP_GATE.faceContrast),
    },
    scenarios: CLOSEUP_SCENARIOS.map((sc) => {
      const H = sc.H;
      // the drawing's integers must stay exact in a double
      for (const x of [0, 4 * width + 3]) {
        for (const y of [0, 4 * height + 3]) {
          const U = H[0]! * x + H[1]! * y + H[2]!;
          const V = H[3]! * x + H[4]! * y + H[5]!;
          const W = H[6]! * x + H[7]! * y + H[8]!;
          const big = Math.max(...CLOSEUP_DRAWING.rings, CLOSEUP_DRAWING.blackR) * W;
          if (!(U * U + V * V < LIMIT && big * big < LIMIT)) throw new Error(`${sc.name}: inexact`);
        }
      }
      const data = syntheticCloseup({ seed: sc.seed, width, height, H, holes: sc.holes });
      const lock = lockCloseupWork(
        closeupWorkImage({ data, width, height }, undefined, CLOSEUP_WORK_LONG_SIDE),
      );
      return {
        name: sc.name,
        seed: sc.seed,
        width,
        height,
        H,
        holes: sc.holes,
        checksum: sum(data),
        passes: passesCloseupGate(lock),
        lock: lock && {
          toMm: lock.toMm.map((v) => new F(v / lock.toMm[8]!)),
          residualMm: new F(lock.residualMm),
          comb: new F(lock.comb),
          ringOffsetMm: lock.ringOffsetMm === null ? null : new F(lock.ringOffsetMm),
          rings: lock.rings,
          voteCenter: [new F(lock.voteCenter.x), new F(lock.voteCenter.y)],
          period: new F(lock.period),
          faceContrast: lock.faceContrast === null ? null : new F(lock.faceContrast),
        },
      };
    }),
  };
}

