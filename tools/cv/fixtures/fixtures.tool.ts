/** Hole-sized crops drawn to exercise the arithmetic, not to look real. */
function crops(): [string, Uint8Array][] {
  const n = HOLE_CROP_PX;
  const rng = new Pcg64(20260916);
  const blank = (v: number) => new Uint8Array(n * n).fill(v);
  const disc = (img: Uint8Array, cx: number, cy: number, r: number, v: number) => {
    for (let y = 0; y < n; y += 1) {
      for (let x = 0; x < n; x += 1) if ((x - cx) ** 2 + (y - cy) ** 2 <= r * r) img[y * n + x] = v;
    }
    return img;
  };
  // np.linspace(0, 255, n), truncated to uint8
  const ramp = (i: number) => (i === n - 1 ? 255 : Math.trunc(i * (255 / (n - 1))));
  const hole = disc(disc(blank(30), n / 2, n / 2, 11, 205), n / 2, n / 2, 5, 70);
  const glyph = blank(30);
  for (let y = 8; y < 40; y += 1) glyph.fill(225, y * n + 20, y * n + 27);
  const noise = rng.bytes(n * n);
  const step = blank(60).map((v, i) => (i % n >= n / 2 ? 190 : v));
  const jitter = rng.integers(-20, 21, n * n);
  return [
    // flat fills
    ['uniform_mid', blank(128)],
    ['uniform_black', blank(0)],
    ['uniform_white', blank(255)],
    // a constant gradient: orientation entropy at its floor, no Laplacian
    ['ramp_x', blank(0).map((_, i) => ramp(i % n))],
    ['ramp_y', blank(0).map((_, i) => ramp(Math.floor(i / n)))],
    // a flat hole-sized blob: the repair-patch shape
    ['flat_patch_dark', disc(blank(30), n / 2, n / 2, 11, 45)],
    ['flat_blob_bright', disc(blank(30), n / 2, n / 2, 11, 210)],
    // a hole: bright rim, darker core, ink round it, and the same on paper
    ['hole_in_black', hole],
    ['hole_on_paper', hole.map((v) => 255 - v)],
    // a printed stroke: straight edges, high contrast, no core
    ['glyph_stroke', glyph],
    // noise, for the high-frequency and Laplacian terms
    ['noise', noise],
    ['step_edge', step],
    ['step_edge_noisy', step.map((v, i) => Math.min(255, Math.max(0, v + jitter[i]!)))],
    // off-centre, so the centre-window term is not always symmetric
    ['corner_blob', disc(blank(40), 10, 10, 8, 220)],
  ];
}

function holeFeatureFixture() {
  return {
    _comment:
      'Generated by tools/cv/fixtures/fixtures.tool.ts (pnpm cv:fixtures) from holeFeatures: a snapshot of the TypeScript, not an independent reference. Every crop is synthetic; no pixel comes from a target photo (hard rule 7).',
    cropPx: HOLE_CROP_PX,
    weights: Object.fromEntries(
      FEATURE_KEYS.map(([k, key]) => [k, new F(HOLE_FILTER_WEIGHTS[key])]),
    ),
    bias: new F(HOLE_FILTER_BIAS),
    threshold: new F(HOLE_PROBABILITY_THRESHOLD),
    cases: crops().map(([name, data]) => {
      const features = holeFeatures({ data, size: HOLE_CROP_PX });
      return {
        name,
        size: HOLE_CROP_PX,
        dataBase64: Buffer.from(data).toString('base64'),
        features: Object.fromEntries(FEATURE_KEYS.map(([k, key]) => [k, new F(features[key])])),
        probability: new F(holeProbability(features)),
      };
    }),
  };
}

