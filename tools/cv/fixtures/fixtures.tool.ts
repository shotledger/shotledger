// ---------------------------------------------------------------- close-up lock

/** Integer `H` for syntheticCloseup: the target centre at image px (cx, cy),
 *  `pxPerMm` along x before `aniso` stretches y, rotated, and a perspective
 *  term (g, h) in the denominator. */
function closeupHomography(
  pxPerMm: number,
  cx: number,
  cy: number,
  { rotDeg = 0, aniso = 1, g = 0, h = 0, w0 = 16384 } = {},
): number[] {
  const k = 8 / (4 * pxPerMm); // target units per quarter px
  const t = rotDeg * (Math.PI / 180);
  const a = k * Math.cos(t);
  const b = k * Math.sin(t);
  const rows: number[] = [];
  for (const [r0, r1] of [
    [a, b],
    [-b / aniso, a / aniso],
  ] as const) {
    const c0 = pyRoundInt(w0 * r0);
    const c1 = pyRoundInt(w0 * r1);
    rows.push(c0, c1, -pyRoundInt(c0 * 4 * cx + c1 * 4 * cy));
  }
  return [...rows, g, h, w0];
}

