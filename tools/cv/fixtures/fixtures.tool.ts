test.skipIf(!process.env.CV_FIXTURES)(
  'write the lock-step fixtures',
  async () => {
    for (const [path, make] of FIXTURES) {
      const file = new URL(path, ROOT).pathname;
      const text = await format(pyJson(make()) + '\n', {
        ...(await resolveConfig(file)),
        filepath: file,
      });
      const before = readFileSync(file, 'utf8');
      writeFileSync(file, text);
      console.log(`${path}: ${before === text ? 'unchanged' : 'rewritten'}`);
    }
  },
  10 * 60 * 1000,
);
