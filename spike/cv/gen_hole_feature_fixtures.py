"""Generate the cross-language fixture that pins the TypeScript port to this file.

`shared/src/target-scoring/hole-features.ts` re-implements `hole_filter.features`
without OpenCV. Nothing but a shared fixture keeps the two honest, so this
writes one: a set of crops, their six feature values as computed here, and the
fitted probability.

    python gen_hole_feature_fixtures.py > \
        ../../shared/src/target-scoring/hole-features.fixtures.json

**Every crop is synthetic.** Not one pixel comes from a target photo — those
are personal data and nothing derived from them may enter the repository (hard
rule 7). The shapes below are drawn from a seeded PRNG and plain geometry, and
exist to exercise the arithmetic (gradients, blur, Laplacian, the centre
window), not to look like real targets.
"""

from __future__ import annotations

import base64
import json
import sys

import numpy as np

import hole_filter as HF

SIZE = HF.CROP


def _blank(value: int) -> np.ndarray:
    return np.full((SIZE, SIZE), value, np.uint8)


def _disc(img, cx, cy, r, value):
    ys, xs = np.mgrid[0:SIZE, 0:SIZE]
    img[(xs - cx) ** 2 + (ys - cy) ** 2 <= r * r] = value


def crops() -> dict[str, np.ndarray]:
    rng = np.random.default_rng(20260916)
    out: dict[str, np.ndarray] = {}

    out["uniform_mid"] = _blank(128)
    out["uniform_black"] = _blank(0)
    out["uniform_white"] = _blank(255)

    # Linear ramps: a constant gradient in one direction, so orientation
    # entropy is at its floor and the Laplacian at zero.
    ramp = np.tile(np.linspace(0, 255, SIZE), (SIZE, 1))
    out["ramp_x"] = ramp.astype(np.uint8)
    out["ramp_y"] = ramp.T.astype(np.uint8)

    # A flat blob the size of a hole: the repair-patch shape.
    patch = _blank(30)
    _disc(patch, SIZE / 2, SIZE / 2, 11, 45)
    out["flat_patch_dark"] = patch
    bright = _blank(30)
    _disc(bright, SIZE / 2, SIZE / 2, 11, 210)
    out["flat_blob_bright"] = bright

    # A hole: bright rim, darker core, ink around it -- and its inverse, the
    # same hole out on the white paper.
    hole = _blank(30)
    _disc(hole, SIZE / 2, SIZE / 2, 11, 205)
    _disc(hole, SIZE / 2, SIZE / 2, 5, 70)
    out["hole_in_black"] = hole
    out["hole_on_paper"] = (255 - hole.astype(np.int16)).astype(np.uint8)

    # A printed glyph: a straight-edged stroke, high contrast, no core.
    glyph = _blank(30)
    glyph[8:40, 20:27] = 225
    out["glyph_stroke"] = glyph

    # Pure noise and noise over a step, to exercise the high-frequency and
    # Laplacian terms where the smooth shapes above cannot.
    out["noise"] = rng.integers(0, 256, (SIZE, SIZE), dtype=np.uint8)
    step = _blank(60)
    step[:, SIZE // 2:] = 190
    out["step_edge"] = step
    noisy = step.astype(np.int16) + rng.integers(-20, 21, (SIZE, SIZE))
    out["step_edge_noisy"] = np.clip(noisy, 0, 255).astype(np.uint8)

    # Off-centre structure, so the centre-window term is not always symmetric.
    corner = _blank(40)
    _disc(corner, 10, 10, 8, 220)
    out["corner_blob"] = corner

    return out


def main() -> None:
    cases = []
    for name, img in crops().items():
        feat = HF.features(img)
        cases.append(dict(
            name=name,
            size=SIZE,
            dataBase64=base64.b64encode(img.reshape(-1).tobytes()).decode(),
            features={k: feat[k] for k in HF.FEATURE_NAMES},
            probability=HF.probability(feat),
        ))
    json.dump(dict(
        _comment=("Generated by spike/cv/gen_hole_feature_fixtures.py. Every crop is "
                  "synthetic; no pixel comes from a target photo (hard rule 7). "
                  "Regenerate whenever hole_filter.features or its constants change."),
        cropPx=SIZE,
        weights=HF.WEIGHTS,
        bias=HF.BIAS,
        threshold=HF.THRESHOLD,
        cases=cases,
    ), sys.stdout, indent=1)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
