--
-- Caliber and load system become closed vocabularies (feat/caliber-and-load-system-presets).
--
-- `firearms.caliber`, `ammo_lots.caliber` and `firearms.load_system` were free
-- text, so `9x19`, `9×19` and `9 mm Luger` were three calibers, and
-- `load_system` held a display string that read back untranslated in the other
-- language ("Halvautomat" in the English UI).
--
-- This migration rewrites what the vocabulary recognises and touches nothing
-- else. No column type changes: the columns stay TEXT with no CHECK, so a
-- value the vocabulary does not recognise survives verbatim rather than being
-- discarded. The picker only offers presets, so such a value can be replaced
-- but never re-entered. That is a deliberate, flagged deviation from
-- "presets only" at the data layer — the alternative was deleting something a
-- user typed.
--
-- The normalisation below mirrors `caliberKey` / `loadSystemKey` in
-- `shared/src/`: case, spacing, `×` vs `x`, a decimal comma and a leading dot
-- stop mattering for calibers; case, punctuation and ä/å/ö stop mattering for
-- load systems. Genuinely ambiguous strings are deliberately absent from both
-- tables and are therefore preserved: bare `.22`, `.45`, `.38`, `.32`, `.30`,
-- `7.62` on the caliber side; "Repeter", "Automat" and "Automatic" on the load
-- system side (rule 4 — the maintainer's call, not a guess).
--
-- `updated_at` is bumped only on rows that actually change, so migration 0004's
-- outbox triggers enqueue exactly those for sync and nothing else.
--
--> statement-breakpoint
CREATE TEMP TABLE `caliber_map` (`k` TEXT PRIMARY KEY, `name` TEXT NOT NULL);
